const translateIndonesian = (value: string) => {
  const exact = indonesian[value];
  if (exact) return exact;

  const dynamicPatterns: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [/^Hello, (.+)$/, (match) => `Halo, ${match[1]}`],
    [/^Created by: (.+)$/, (match) => `Dibuat oleh: ${match[1]}`],
    [/^Created by (.+)$/, (match) => `Dibuat oleh ${match[1]}`],
    [/^Deadline by (.+)$/, (match) => `Tenggat oleh ${match[1]}`],
    [/^Must do: (.+)$/, (match) => `Dikerjakan oleh: ${match[1]}`],
    [/^Must do it: (.+)$/, (match) => `Harus dikerjakan oleh: ${match[1]}`],
    [/^Users in task: (.+)$/, (match) => `Pengguna dalam tugas: ${match[1]}`],
    [/^Deadline: (.+)$/, (match) => `Tenggat: ${match[1]}`],
    [/^App: (.+)$/, (match) => `Aplikasi: ${match[1]}`],
    [/^Applied (.+)$/, (match) => `Dilamar ${match[1]}`],
    [/^Done (\d+)$/, (match) => `Selesai ${match[1]}`],
    [/^Failed (\d+)$/, (match) => `Gagal ${match[1]}`],
    [/^Ongoing (\d+)$/, (match) => `Berlangsung ${match[1]}`],
    [/^(\d+) alerts?$/, (match) => `${match[1]} pengingat`],
    [/^(\d+) applied · (\d+) cancelled$/, (match) =>
      `${match[1]} lamaran · ${match[2]} dibatalkan`],
    [/^Every day at (.+)$/, (match) => `Setiap hari pukul ${match[1]}`],
    [/^(\d+) tasks? missed the deadline$/, (match) => `${match[1]} tugas melewati tenggat`],
    [/^(\d+) Subtasks$/, (match) => `${match[1]} subtugas`],
    [/^(.+)'s Overview$/, (match) => `Ringkasan ${match[1]}`],
    [/^(\d+) application(s?) · (\d+) interview(s?)$/, (match) =>
      `${match[1]} lamaran · ${match[3]} wawancara`],
    [/^Daily at (.+?)(?: · until (.+))?$/, (match) =>
      `Setiap hari pukul ${match[1]}${match[2] ? ` · sampai ${match[2]}` : ''}`],
    [/^Daily from (.+?) to (.+)$/, (match) => `Setiap hari dari ${match[1]} sampai ${match[2]}`],
    [/^Daily from (.+) onward$/, (match) => `Setiap hari mulai ${match[1]} dan seterusnya`],
    [/^(?:Daily at (.+?) · )?Subtasks done: (.+)$/, (match) =>
      `${match[1] ? `Setiap hari pukul ${match[1]} · ` : ''}Subtugas selesai: ${match[2]}`],
    [/^Deadline (.+)$/, (match) => `Tenggat ${match[1]}`],
    [/^Started (.+)$/, (match) => `Dimulai ${match[1]}`],
    [/^From (.+) onward$/, (match) => `Mulai ${match[1]} dan seterusnya`],
    [/^(.+) to (.+)$/, (match) => `${match[1]} sampai ${match[2]}`],
    [/^Select (start date|deadline)$/, (match) =>
      `Pilih ${match[1] === 'start date' ? 'tanggal mulai' : 'tenggat'}`],
    [/^Already occupied by: (.+)$/, (match) => `Sudah diisi oleh: ${match[1]}`],
  ];

  for (const [pattern, format] of dynamicPatterns) {
    const match = value.match(pattern);
    if (match) return format(match);
  }
  return value;
};

export function LocalizedText({ children, ...props }: TextProps) {
  const { language } = useAppSettings();
  const text = typeof children === 'string' || typeof children === 'number'
    ? String(children)
    : Array.isArray(children) && children.every((child) => typeof child === 'string' || typeof child === 'number')
      ? children.map(String).join('')
      : null;

  return (
    <Text {...props}>
      {text !== null && language === 'id' ? translateIndonesian(text) : children}
    </Text>
  );
}

export function LocalizedTextInput({ placeholder, accessibilityLabel, ...props }: TextInputProps) {
  const { language } = useAppSettings();
  return (
    <TextInput
      {...props}
      accessibilityLabel={language === 'id' && accessibilityLabel ? translateIndonesian(accessibilityLabel) : accessibilityLabel}
      placeholder={language === 'id' && placeholder ? translateIndonesian(placeholder) : placeholder}
    />
  );
}

export const translate = (value: string, language: 'en' | 'id') =>
  language === 'id' ? translateIndonesian(value) : value;
